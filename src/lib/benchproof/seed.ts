function finish(
  claim: Omit<ClaimRecord, "evaluation" | "transactions"> & { evaluation?: ClaimRecord["evaluation"] },
): ClaimRecord {
  const evaluation = forensicEvaluate({
    title: claim.title,
    statement: claim.statement,
    modelA: claim.modelA,
    modelAVersion: claim.modelAVersion,
    modelB: claim.modelB,
    modelBVersion: claim.modelBVersion,
    benchmark: claim.benchmark,
    benchmarkVersion: claim.benchmarkVersion,
    evaluationDate: claim.evaluationDate,
    metric: claim.metric,
    reportedResult: claim.reportedResult,
    methodology: claim.methodology,
    sourceUrls: claim.sourceUrls,
    conditions: claim.conditions,
    evidence: claim.evidence,
    challenges: claim.challenges,
  });
  evaluation.source = "seed";
  evaluation.evaluatedAt = claim.publishedAt || claim.createdAt;
  return { ...claim, evaluation, transactions: [], status: "OPEN", txState: "submitted" };
}

