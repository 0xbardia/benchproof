import { forensicEvaluate } from "./evaluate.ts";
import { hashEvidence } from "./hash.ts";
import { EMPTY_CONDITIONS, type ClaimRecord, type Conditions } from "./types.ts";

function cond(partial: Partial<Conditions>): Conditions {
  return { ...EMPTY_CONDITIONS, ...partial };
}

function ev(
  claimId: string,
  idx: number,
  kind: ClaimRecord["evidence"][number]["kind"],
  uri: string,
  note: string,
) {
  const contentHash = hashEvidence({ kind, uri, note });
  return {
    id: `${claimId}-ev-${idx}`,
    claimId,
    kind,
    uri,
    contentHash,
    note,
    addedAt: "2026-08-12T10:00:00.000Z",
    onchainIndex: idx,
  };
}

